"""Aggregate per-seed results from run_three_layer_seed_study.py into a table."""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[1]
DATA = REPO_ROOT / "graphs" / "data"
TARGET_PCT = 5.0

ORDER = [
    "Full framework",
    "- Compliance-aware scaling",
    "- Layerwise PDE decomposition",
    "- Interface continuity",
    "- Sparse FEM supervision",
    "Vanilla PINN baseline",
]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--study-dir", default=str(DATA / "three_layer_seed_study"))
    parser.add_argument("--out-csv", default=str(DATA / "three_layer_seed_study_summary.csv"))
    parser.add_argument("--paper-csv", default=str(DATA / "three_layer_paper_ablation.csv"),
                        help="Paper-facing ablation table generated from the per-seed results.")
    args = parser.parse_args()

    runs: dict[str, list[dict]] = {}
    for path in sorted(Path(args.study_dir).glob("*/seed_*/result.json")):
        r = json.loads(path.read_text())
        runs.setdefault(r["variant"], []).append(r)

    rows = []
    for variant in [v for v in ORDER if v in runs] + [v for v in runs if v not in ORDER]:
        rs = runs[variant]
        mean = np.array([r["volume_mae_pct_mean"] for r in rs])
        worst = np.array([r["volume_mae_pct_worst"] for r in rs])
        rows.append(
            {
                "variant": variant,
                "n_seeds": len(rs),
                "mean_volmae_avg": f"{mean.mean():.3f}",
                "mean_volmae_std": f"{mean.std(ddof=1) if len(rs) > 1 else float('nan'):.3f}",
                "mean_volmae_min": f"{mean.min():.3f}",
                "mean_volmae_max": f"{mean.max():.3f}",
                "worst_volmae_avg": f"{worst.mean():.3f}",
                "worst_volmae_std": f"{worst.std(ddof=1) if len(rs) > 1 else float('nan'):.3f}",
                "worst_volmae_min": f"{worst.min():.3f}",
                "worst_volmae_max": f"{worst.max():.3f}",
                "seeds_worst_below_target": f"{int((worst < TARGET_PCT).sum())}/{len(rs)}",
                "eval_seeds": sorted({r["eval_seed"] for r in rs}).__str__(),
                "git_hashes": sorted({r["git_hash"] for r in rs}).__str__(),
            }
        )

    with open(args.out_csv, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=rows[0].keys())
        writer.writeheader()
        writer.writerows(rows)

    removed = {
        "Full framework": "none",
        "- Compliance-aware scaling": "compliance_aware_scaling",
        "- Layerwise PDE decomposition": "layerwise_pde_decomposition",
        "- Interface continuity": "interface_continuity",
        "- Sparse FEM supervision": "sparse_fem_supervision",
        "Vanilla PINN baseline": "baseline",
    }
    with open(args.paper_csv, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["variant", "removed_component", "n_seeds", "mean_volmae", "mean_volmae_std",
                         "worst_volmae", "worst_volmae_std", "source_note"])
        for r in rows:
            writer.writerow([r["variant"], removed.get(r["variant"], ""), r["n_seeds"],
                             r["mean_volmae_avg"], r["mean_volmae_std"],
                             r["worst_volmae_avg"], r["worst_volmae_std"],
                             "Generated by scripts/aggregate_seed_study.py from graphs/data/three_layer_seed_study_gpu/*/seed_*/result.json"])

    for r in rows:
        print(
            f"{r['variant']:<32} n={r['n_seeds']:<3} "
            f"mean {r['mean_volmae_avg']}±{r['mean_volmae_std']} "
            f"[{r['mean_volmae_min']}, {r['mean_volmae_max']}]  "
            f"worst {r['worst_volmae_avg']}±{r['worst_volmae_std']} "
            f"[{r['worst_volmae_min']}, {r['worst_volmae_max']}]  "
            f"<{TARGET_PCT:g}%: {r['seeds_worst_below_target']}"
        )
    print(f"Wrote {args.out_csv} and {args.paper_csv}")


if __name__ == "__main__":
    main()
